def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    ids_in_file = {c["id"] for c in d["cases"]}
    missing = sorted(set(ZH) - ids_in_file)
    if missing:
        print(f"[FAIL] 映射表含文件中不存在的 id: {missing[:5]}…")
        return 1
    translated = kept = 0
    for c in d["cases"]:
        zh = ZH.get(c["id"])
        if zh is None:
            continue  # 定义门 9 条本就是中文
        if not c.get("titleEn"):
            c["titleEn"] = c["title"]
        if re.search(r"[一-鿿]", c["title"]):
            kept += 1  # 已汉化（幂等重跑）
        else:
            c["title"] = zh
            translated += 1
    d["note"] = d.get("note", "").rstrip("。") + "。标题已汉化（2026-09-20 迁移，tools/translate_case_titles_20260920.py），脚本门英文原题保留于 titleEn 字段。"
    SRC.write_text(json.dumps(d, ensure_ascii=False), encoding="utf-8")
    print(f"[OK] 新汉化 {translated} | 已是中文跳过 {kept} | 总 {len(d['cases'])} 条")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
